import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import chalk from "chalk";
import dotenv from "dotenv";
import ora from "ora";
import { execa } from "execa";
import { runDiagnosis } from "../core/diagnose.js";
import { installCommand } from "../core/project.js";

function templateFor(vars: string[], file: string): string {
  const lines = [
    `# Generated by EnvMedic — ${file}`,
    "# Fill in real values locally. Never commit secrets.",
    "",
    ...vars.map((v) => `${v}=`),
  ];
  return `${lines.join("\n")}\n`;
}

export async function runFix(
  cwd: string,
  opts?: { dryRun?: boolean },
): Promise<void> {
  const dry = !!opts?.dryRun;
  console.log(chalk.bold("\n🔧 EnvMedic Fix\n"));

  const spinner = ora("Diagnosing...").start();
  let d;
  try {
    d = await runDiagnosis(cwd);
  } catch (err) {
    spinner.fail(`Diagnosis failed: ${(err as Error).message}`);
    throw err;
  }
  spinner.stop();

  if (d.score === 100) {
    console.log(chalk.green("Nothing to fix — environment is healthy.\n"));
    return;
  }

  const applied: string[] = [];
  const manual: string[] = [];

  // 1. Install missing dependencies (safe, project-level) — but not when
  // the manifest itself is corrupt; npm would just fail confusingly.
  if (!d.nodeModulesPresent && d.hasPackageJson && !d.pkgCorrupt) {
    const cmd = installCommand(d.packageManager);
    if (dry) {
      applied.push(`[dry-run] would run: ${cmd}`);
    } else {
      const s = ora(`Running ${cmd}...`).start();
      try {
        await execa(cmd.split(" ")[0] as string, cmd.split(" ").slice(1), {
          cwd,
          stdio: "inherit",
        });
        s.succeed("Dependencies installed");
        applied.push("Installed dependencies");
      } catch (err) {
        s.fail(`Install failed: ${(err as Error).message}`);
        manual.push(`Run \`${cmd}\` and read the error output`);
      }
    }
  }

  // 2. Create .env.example from detected names (values are never written).
  if (d.envRequired.length > 0 && !existsSync(join(cwd, ".env.example"))) {
    const content = templateFor(d.envRequired, ".env.example");
    if (dry) {
      applied.push(`[dry-run] would create .env.example (${d.envRequired.length} vars)`);
    } else {
      writeFileSync(join(cwd, ".env.example"), content, "utf-8");
      applied.push(`Created .env.example (${d.envRequired.length} vars, no values)`);
    }
  }

  // 2b. Complete an existing .env.example by APPENDING absent names only.
  // Existing lines (and any values in them) are never touched.
  const examplePath = join(cwd, ".env.example");
  if (d.envRequired.length > 0 && existsSync(examplePath)) {
    let raw = "";
    try {
      raw = readFileSync(examplePath, "utf-8");
    } catch {
      raw = "";
    }
    let present: string[] = [];
    try {
      present = Object.keys(dotenv.parse(raw));
    } catch {
      present = [];
    }
    const absent = d.envRequired.filter((v) => !present.includes(v));
    if (absent.length > 0) {
      if (dry) {
        applied.push(`[dry-run] would append ${absent.join(", ")} to .env.example`);
      } else {
        const suffix = absent.map((v) => `${v}=`).join("\n");
        const glue = raw.length === 0 || raw.endsWith("\n") ? "" : "\n";
        writeFileSync(examplePath, `${raw}${glue}${suffix}\n`, "utf-8");
        applied.push(`Completed .env.example (appended ${absent.join(", ")})`);
      }
    }
  }
  // 3. Create .env.local template — never overwrite existing files.
  const hasLocal = existsSync(join(cwd, ".env.local")) || existsSync(join(cwd, ".env"));
  if (d.envRequired.length > 0 && !hasLocal) {
    const content = templateFor(d.envRequired, ".env.local");
    if (dry) {
      applied.push("[dry-run] would create .env.local template (empty values)");
    } else {
      writeFileSync(join(cwd, ".env.local"), content, "utf-8");
      applied.push("Created .env.local template (fill in real values)");
    }
  }

  // 4. Ports: report only — never kill processes silently.
  for (const p of d.ports) {
    if (p.occupied) {
      const alt = p.alternatives[0];
      manual.push(
        alt
          ? `Port ${p.port} occupied — free it or run with PORT=${alt}`
          : `Port ${p.port} occupied — free it manually`,
      );
    }
  }

  // 5. Missing secret values always need a human.
  for (const name of d.envMissing) {
    if (!manual.some((m) => m.includes(name))) {
      manual.push(`Add ${name} to .env.local (value required, cannot auto-generate)`);
    }
  }

  // Report.
  if (applied.length > 0) {
    console.log(chalk.green("Applied:\n"));
    for (const a of applied) console.log(`  ✅ ${a}`);
  }
  if (manual.length > 0) {
    console.log(chalk.yellow("\nNeeds your action:\n"));
    manual.forEach((m, i) => console.log(`  ${i + 1}. ${m}`));
  }
  if (applied.length === 0 && manual.length === 0) {
    // Genuine failures exist (score < 100) but nothing is safely automatable.
    // Surface them instead of claiming health.
    const remaining = d.results.filter((r) => r.status === "fail");
    console.log(chalk.yellow("\nNo safe automatic fixes apply. Remaining problems:\n"));
    for (const r of remaining) console.log(`  🔴 [${r.name}] ${r.message}`);
  }
  console.log(chalk.dim("\nRe-run `envmedic doctor` to verify.\n"));
}
